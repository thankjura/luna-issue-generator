package ru.slie.luna.rest.client.model;

public class RemoteProject {
    private Long id;
    private String key;
    private String name;
    private String description;

    public Long getId() {
        return id;
    }

    public String getKey() {
        return key;
    }

    public String getName() {
        return name;
    }

    public String getDescription() {
        return description;
    }
}
